/** Lookup a discussion by id or slug. */
export function getDiscussion(idOrSlug: string): Discussion | undefined {
  return DISCUSSIONS.find((d) => d.id === idOrSlug || d.slug === idOrSlug);
}

export function getRepliesForDiscussion(id: string): DiscussionReply[] {
  const discussion = getDiscussion(id);
  const key = discussion?.id ?? id;
  return DISCUSSION_REPLIES.filter((r) => r.discussionId === key).sort(
    (a, b) => new Date(a.createdAt).getTime() - new Date(b.createdAt).getTime(),
  );
}

export function getTrendingDiscussions(n = 5): Discussion[] {
  return [...DISCUSSIONS]
    .filter((d) => d.moderationState !== "locked")
    .sort((a, b) => b.upvotes + b.viewCount / 20 - (a.upvotes + a.viewCount / 20))
    .slice(0, n);
}
