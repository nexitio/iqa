export function getQuestion(idOrSlug: string): Question | undefined {
  return QUESTIONS.find((q) => q.id === idOrSlug || q.slug === idOrSlug);
}

/** Accepted answer first, then by community score. */
export function getAnswersForQuestion(questionId: string): Answer[] {
  return ANSWERS.filter((a) => a.questionId === questionId).sort(
    (a, b) =>
      Number(b.accepted) - Number(a.accepted) ||
      b.upvotes - b.downvotes - (a.upvotes - a.downvotes),
  );
}

export function getAnswersByScholar(scholarId: string): Answer[] {
  return ANSWERS.filter((a) => a.scholarId === scholarId);
}

export function getRoutingCandidates(questionId: string): RoutingCandidate[] {
  return (ROUTING_CANDIDATES[questionId] ?? []).slice().sort((a, b) => b.score - a.score);
}

/** Questions still waiting for their first answer, newest first. */
export function getUnansweredQuestions(): Question[] {
  return QUESTIONS.filter((q) => q.answerCount === 0 && q.status !== "closed").sort(
    (a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime(),
  );
}

export const ANSWERED_QUESTIONS: Question[] = QUESTIONS.filter((q) => q.status === "answered");

export const URGENT_QUESTIONS: Question[] = QUESTIONS.filter((q) => q.urgency === "urgent");

