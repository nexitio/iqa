/**
 * Score the authored-library suggestions against a draft.
 *
 * This is the real matcher the composer uses: Bangla keyword presence decides
 * relevance. When a draft is still empty nothing matches, so the highest-scoring
 * suggestions are offered as a sensible starting point.
 */
export function getSuggestionsForKeywords(text: string): ReferenceSuggestion[] {
  const haystack = text.toLowerCase();
  if (haystack.trim().length === 0) {
    return [...REFERENCE_SUGGESTIONS].sort((a, b) => b.score - a.score).slice(0, 6);
  }

  const matches = REFERENCE_SUGGESTIONS.filter((s) =>
    s.matchedTerms.some((term) => haystack.includes(term.toLowerCase())),
  );

  if (matches.length === 0) {
    return [...REFERENCE_SUGGESTIONS].sort((a, b) => b.score - a.score).slice(0, 6);
  }
  return matches.sort((a, b) => b.score - a.score);
}

