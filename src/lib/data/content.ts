export const ARTICLE_BY_SLUG: Record<string, Article> = Object.fromEntries(
  ARTICLES.map((a) => [a.slug, a]),
);

export const FATWA_BY_SLUG: Record<string, Fatwa> = Object.fromEntries(
  FATWAS.map((f) => [f.slug, f]),
);

/** Accepts either an id ("art-1") or a slug. */
export function getArticle(idOrSlug: string): Article | undefined {
  return ARTICLES.find((a) => a.id === idOrSlug || a.slug === idOrSlug);
}

export function getFatwa(idOrSlug: string): Fatwa | undefined {
  return FATWAS.find((f) => f.id === idOrSlug || f.slug === idOrSlug);
}

export function getArticlesByDepartment(departmentSlug: string): Article[] {
  return ARTICLES.filter((a) => a.departmentIds.includes(departmentSlug));
}

export function getArticlesByAuthor(scholarId: string): Article[] {
  return ARTICLES.filter((a) => a.authorId === scholarId);
}

export function getFatwasByMufti(scholarId: string): Fatwa[] {
  return FATWAS.filter((f) => f.muftiId === scholarId || f.coSignerIds.includes(scholarId));
}

/** Fatwas sharing a department with the given one, pinned first. */
export function getRelatedFatwas(fatwa: Fatwa, n = 3): Fatwa[] {
  return FATWAS.filter(
    (f) => f.id !== fatwa.id && f.departmentIds.some((d) => fatwa.departmentIds.includes(d)),
  )
    .sort((a, b) => Number(b.pinned) - Number(a.pinned) || b.viewCount - a.viewCount)
    .slice(0, n);
}

