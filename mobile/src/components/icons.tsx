/**
 * The data layer stores icon *names* (e.g. `Department.icon = "Scale"`), so this
 * is the single place those names resolve to components — the RN equivalent of
 * the web app's `components/icons.tsx`.
 */
const ICON_MAP: Record<string, LucideIcon> = {
  Sparkles,
  Scale,
  BookOpen,
  Library,
  ScrollText,
  Users,
  Coins,
  HeartHandshake,
  HandHeart,
  GraduationCap,
  MoonStar,
  Utensils,
  Plane,
  HeartPulse,
  LifeBuoy,
  Home,
  Building2,
  Route,
  Compass,
  FileText,
  MessagesSquare,
  MessageCircleQuestion,
};

export function resolveIcon(name: string | undefined): LucideIcon {
  return (name && ICON_MAP[name]) || Sparkles;
}

